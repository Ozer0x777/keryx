export default async ({ stack, BASE, check, login }) => {
  const m = await login('manager')
  await m.getByRole('link', { name: 'Pilotage' }).click()
  await m.waitForSelector('text=Charge par analyste')
  check(await m.locator('.stat').count() === 5, 'tableau de bord : 5 indicateurs')
  check(await m.locator('.trend svg rect').count() > 0, 'graphique d\'évolution tracé')
  check(await m.locator('.barlist li').count() >= 4, 'barres par gravité')
  check(await m.locator('tbody tr', { hasText: 'Test analyste' }).count() === 1, 'charge par analyste')
  await m.getByRole('link', { name: 'Rapports et registre' }).click()
  await m.waitForSelector('.report')
  check(await m.locator('.report tbody tr').count() >= 2, 'rapport périodique listé')
  const [dl] = await Promise.all([m.waitForEvent('download'), m.getByRole('button', { name: 'Exporter le registre (CSV)' }).click()])
  check(dl.suggestedFilename().startsWith('registre-ACME'), 'export CSV du registre')
  await m.goto(`${BASE}/tickets/ACME-1`)
  await m.getByRole('link', { name: 'Rapport imprimable' }).click()
  await m.waitForSelector("text=Rapport d'incident ACME-1")
  check(await m.locator('text=Registre des actions').count() > 0, 'rapport d\'incident imprimable')
  check(m.errors.length === 0, 'aucune erreur JavaScript')
  await m.context().close()
}
