import { answerDialog, unfold, until } from '../harness.mjs'

export default async ({ stack, BASE, check, login }) => {
  const send = (alert) => fetch(`${BASE}/api/v1/ingest/wazuh`, { method: 'POST', headers: { Authorization: `Bearer ${stack.seeds.apiKey}`, 'Content-Type': 'application/json' }, body: JSON.stringify(alert) }).then((r) => r.json())
  const base = { timestamp: '2026-11-20T14:41:02.118+0000', rule: { id: '5712', level: 10, description: 'sshd: brute force', groups: ['sshd'] }, agent: { id: '003', name: 'srv-web-01', ip: '10.20.1.15' }, full_log: 'x' }
  check((await send({ ...base, id: 'a1' })).status === 'created', 'alerte 1 ingérée')
  check((await send({ ...base, id: 'b1', rule: { ...base.rule, id: '5999', description: 'ftp: login failed' }, agent: { id: '004', name: 'srv-ftp', ip: '10.20.1.16' } })).status === 'created', 'alerte 2 ingérée')

  const m = await login('manager')
  await m.goto(`${BASE}/tickets`)
  await m.waitForSelector('text=ACME-2')
  // recherche
  await m.fill('input[type=search]', 'ftp'); await m.keyboard.press('Enter')
  await until(async () => (await m.locator('tbody tr').count()) === 1, '1 ligne')
  check(await m.locator('tbody tr').first().innerText().then((t) => t.includes('ACME-2')), 'recherche plein texte')
  await m.getByRole('button', { name: 'Réinitialiser' }).click()
  await until(async () => (await m.locator('tbody tr').count()) === 2, '2 lignes')
  // tri par référence croissante
  await m.getByRole('button', { name: /^Réf\./ }).click()
  await m.getByRole('button', { name: /^Réf\./ }).click()
  await m.waitForTimeout(500)
  check((await m.locator('tbody tr').first().innerText()).includes('ACME-1'), 'tri par référence')
  check(m.url().includes('sort=ref') && m.url().includes('order=asc'), "le tri est inscrit dans l'URL")
  // affectation en masse, avec la case « tout sélectionner » de la page
  await m.getByLabel('Sélectionner tous les tickets affichés').check()
  check(await m.locator('tbody input[type=checkbox]:checked').count() === 2 && (await m.locator('.bulkbar strong').innerText()).startsWith('2'), 'tout sélectionner : les 2 lignes de la page sont cochées')
  await m.uncheck('input[aria-label="Sélectionner ACME-2"]')
  check(await m.getByLabel('Sélectionner tous les tickets affichés').evaluate((e) => e.indeterminate && !e.checked), 'tout sélectionner : état intermédiaire quand une ligne est décochée')
  await m.check('input[aria-label="Sélectionner ACME-2"]')
  await m.waitForSelector('.bulkbar select option:has-text("Test analyste")', { state: 'attached' })
  await m.selectOption('.bulkbar select', 'analyste')
  await m.waitForSelector('text=2 ticket(s) affecté(s)')
  check(true, 'affectation en masse')
  // cartes de chiffres = filtres ; tri par criticité ; état conservé dans l'URL et restauré au retour d'un ticket
  const carte = m.getByRole('button', { name: /^À qualifier/ })
  check(await carte.getAttribute('aria-pressed') === 'false', 'carte « À qualifier » : bouton à bascule, relâché par défaut')
  await carte.click()
  await until(async () => await carte.getAttribute('aria-pressed') === 'true', 'carte enfoncée')
  await m.getByRole('button', { name: /^Criticité/ }).click()
  await until(async () => m.url().includes('sort=criticite'), 'tri criticité')
  check(m.url().includes('status=nouveau%2Cen_evaluation'), "le filtre de la carte est inscrit dans l'URL")
  check(await m.locator('th[aria-sort=descending]').innerText().then((t) => t.startsWith('CRITICITÉ') || t.startsWith('Criticité')), 'tri par criticité, du plus grave au moins grave')
  check(await m.locator('select').first().inputValue() === 'nouveau,en_evaluation', 'la liste « Statut » reflète le filtre de la carte')
  const listUrl = m.url()
  await m.locator('tbody a', { hasText: 'ACME-1' }).click()
  await m.waitForSelector('.ticket-head')
  await m.locator('.breadcrumb a').first().click()
  await m.waitForSelector('tbody tr')
  check(m.url() === listUrl && await carte.getAttribute('aria-pressed') === 'true', "retour d'un ticket par le fil d'Ariane : filtres et tri restaurés")
  await m.locator('tbody a', { hasText: 'ACME-1' }).click(); await m.waitForSelector('.ticket-head'); await m.goBack(); await m.waitForSelector('tbody tr')
  check(m.url() === listUrl && await m.locator('th[aria-sort=descending]').count() === 1, 'retour par le bouton Précédent : filtres et tri restaurés')
  // relevé : heure du dernier relevé et bouton Actualiser
  await m.waitForSelector('tbody a')
  check(/Mis à jour à \d\d:\d\d UTC/.test(await m.locator('.refresh').innerText()), 'heure du dernier relevé affichée (UTC)')
  const lists = []
  m.on('request', (r) => { if (/\/api\/v1\/tickets\?.*limit=\d+/.test(r.url())) lists.push(r.url()) })   // la liste, pas la synthèse
  await m.getByRole('button', { name: 'Actualiser' }).click()
  await until(async () => lists.length >= 1, 'relevé manuel')
  check(lists[0].includes('sort=criticite'), 'Actualiser relance la liste avec les filtres en cours')
  await carte.click()
  await until(async () => await carte.getAttribute('aria-pressed') === 'false', 'carte relâchée')
  check(!m.url().includes('status='), 'recliquer la carte retire son filtre')
  // fiche d'un ticket « Nouveau » : échéance et assigné dans l'en-tête, seuls les panneaux utiles au triage sont ouverts
  await m.goto(`${BASE}/tickets/ACME-1`)
  await m.waitForSelector('.ticket-facts')
  const facts = await m.locator('.ticket-facts').innerText()
  check(facts.includes('Qualifier avant') && facts.includes('Résoudre avant') && facts.includes('UTC'), "en-tête : échéances de qualification et de résolution (UTC)")
  check(facts.includes('Assigné à') && facts.includes('Test analyste'), "en-tête : assigné du ticket")
  await m.waitForSelector('section[aria-label="Affectation"]')
  const ouverts = await m.locator('.fold > details[open]').evaluateAll((l) => l.map((d) => d.parentElement.getAttribute('aria-label')))
  // Formulaires de la phase ouverts ; un panneau de contenu s'ouvre s'il est rempli (le registre des actions l'est dès la création).
  check(JSON.stringify(ouverts) === JSON.stringify(['Description', 'Qualification', 'Affectation', 'Registre des actions']), `statut Nouveau : description, qualification et affectation ouvertes, registre des actions ouvert car rempli, le reste replié (${ouverts.join(', ')})`)
  check(await m.locator('section[aria-label="Alerte Wazuh"]').count() === 0 && await m.locator('.alert-extra').count() === 1, "l'alerte déjà reprise par la description n'est pas répétée dans un second panneau")
  check(await m.locator('.ticket-steps button.primary').count() === 1, 'un seul bouton primaire parmi les étapes de la barre fixe')
  check(await m.evaluate(() => getComputedStyle(document.querySelector('.ticket-aside')).position) !== 'sticky', 'colonne de pilotage non collante')
  // lien entre tickets depuis la fiche
  await unfold(m, 'Tickets liés')
  await m.fill('input[placeholder="ACME-2"]', 'ACME-2'); await m.getByRole('button', { name: 'Lier', exact: true }).click()
  await m.waitForSelector('.linklist >> text=ACME-2')
  check(true, 'lien créé depuis la fiche')
  // éditeur riche : l'état actif d'un bouton suit la mise en forme (classe et aria-pressed)
  await unfold(m, 'Commentaires')
  await m.locator('section[aria-label="Commentaires"] .rich-content').last().click()
  const gras = m.locator('section[aria-label="Commentaires"] .tool[title="Gras"]')
  check(await gras.getAttribute('aria-pressed') === 'false', 'éditeur : bouton Gras relâché par défaut')
  await gras.click(); await m.keyboard.type('x')
  check(await gras.getAttribute('aria-pressed') === 'true' && (await gras.getAttribute('class')).includes('on'), 'éditeur : bouton Gras marqué actif (aria-pressed et style)')
  await gras.click(); await m.keyboard.press('Backspace')
  // modèle enregistré depuis un commentaire
  await m.locator('section[aria-label="Commentaires"] .rich-content').last().click(); await m.keyboard.type('Accusé de réception, analyse en cours.')
  await m.getByRole('button', { name: 'Enregistrer comme modèle' }).click()
  await answerDialog(m, { name: 'Accusé' })
  await m.waitForSelector('text=Modèle enregistré.')
  check(true, 'modèle enregistré (nom saisi dans le dialogue)')
  // dialogue de fusion : deux champs, validation en ligne, Échap ferme et rend le focus au déclencheur
  await m.getByRole('tab', { name: 'Vue générale' }).click()   // la fusion est dans l'onglet Vue générale
  const fusion = m.getByRole('button', { name: 'Fusionner dans un autre ticket…' })
  await fusion.click()
  const d = await answerDialog(m, { into: 'ACME-2', reason: 'x' }, { stays: true })
  check(await d.locator('.field-error').count() === 1 && (await d.locator('.field-error').innerText()).includes('au moins 3'), 'fusion : motif trop court signalé sous le champ, dialogue resté ouvert')
  check(await d.locator('[name=reason]').getAttribute('aria-invalid') === 'true' && await d.locator('[name=reason]').evaluate((e) => e === document.activeElement), 'fusion : le champ en erreur est marqué et reçoit le focus')
  check((await d.locator('h2').innerText()).includes('ACME-1') && (await d.locator('button[type=submit]').innerText()) === 'Fusionner et clore', 'fusion : titre avec l\'objet et la conséquence, bouton nommé par le verbe')
  await d.locator('[name=reason]').focus()
  for (let i = 0; i < 6; i++) await m.keyboard.press('Tab')
  check(await m.evaluate(() => !!document.activeElement.closest('dialog[open]') || document.activeElement === document.body), 'fusion : le focus reste dans le dialogue (tabulation)')
  await m.keyboard.press('Escape')
  await d.waitFor({ state: 'detached' })
  check(await fusion.evaluate((e) => e === document.activeElement), 'fusion : Échap ferme le dialogue et rend le focus au bouton')
  check((await m.locator('.ticket-head .status').innerText()).includes('Nouveau'), 'fusion annulée : le ticket n\'a pas changé de statut')
  await m.context().close()

  // l'analyste reçoit la notification d'affectation (cloche) et filtre « Mes tickets »
  const a = await login('analyste')
  await a.waitForSelector('.bell-count')
  check((await a.locator('.bell-count').innerText()).trim() === '2', 'cloche : 2 notifications non lues')
  await a.getByRole('button', { name: /Notifications/ }).click()
  await a.waitForSelector('.bell-panel >> text=Ticket affecté')
  check(true, 'liste des notifications')
  await a.locator('.bell-panel li button').first().click()
  await a.waitForURL(/\/tickets\/ACME-/)
  await a.goto(`${BASE}/tickets`)
  await a.getByRole('button', { name: 'Mes tickets' }).click()
  await until(async () => (await a.locator('tbody tr').count()) === 2, '2 lignes')
  check(true, 'vue Mes tickets')
  // modèle visible côté ticket
  await a.goto(`${BASE}/tickets/ACME-1`)
  await unfold(a, 'Commentaires')
  await a.waitForSelector('section[aria-label="Commentaires"] select[aria-label="Insérer un modèle"]')
  check(true, 'modèle proposé à l\'éditeur')
  check(a.errors.length === 0, 'aucune erreur JavaScript')
  await a.context().close()
}
